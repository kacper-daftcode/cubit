#[test]
fn bug038_census_renders_native_text_and_roundtrips() {
    let t = t120();
    let idx = DecodeIndex::build(&t);
    let mut fails = Vec::new();
    for &(_, addr, word, golden) in WORDS {
        let d = match idx.decode(word, addr, &t) {
            Ok(d) => d,
            Err(e) => { fails.push(format!("0x{addr:04x}: decode fail: {e}")); continue; }
        };
        let text = cubit::printer::to_sass(&d);
        if text != golden {
            fails.push(format!("0x{addr:04x}: render {text:?} != golden {golden:?}"));
            continue;
        }
        // text -> encode -> same word (sched bits excluded: encoder emits its own)
        let insn = parse_sass(&format!("{text} ;"), addr).unwrap();
        let w2 = encode_instruction(&insn, &t).unwrap();
        if (w2 & !SCHED) != (word & !SCHED) {
            fails.push(format!("0x{addr:04x}: re-encode word diff {w2:032x} vs {word:032x}"));
        }
    }
    assert!(fails.is_empty(), "{} failures:\n{}", fails.len(), fails[..5].join("\n"));
}

#[test]
fn bug038_ldg_sink_still_serves_legacy_words() {
    // BUG-094 retired this pin's original shape: the "sink" was the harvest
    // junk modgroup LDG_R_dARI::128,E,LTC128B (and_base 0x980) decoding
    // self-shaped words. Word-level nvdisasm-13.3 truth for the synthetic
    // self-word is `@P0 LD.EF.U8 R0, [R0]` — an LD.EF class with ZERO anchors
    // in the 2049-cubin gate corpus and both census universes (885k words);
    // neither table carries LD.EF.U8 coverage today (b4-feed note,
    // results/cubitfix/094/NOTE_sink_ld_ef.md). Decode is therefore
    // FAIL-CLOSED now; re-pin to the LD.EF truth when coverage lands.
    // b4fill4 (F2-iter38): coverage landed — 25 additive LD_R_ARI mod groups
    // (full LD ARI family incl. .EF) with per-row probe anchors; the sink word
    // now decodes to its vendor-true identity (pinned in
    // b4fill4_ldef_family.rs::b4fill4_ldef_sink_is_vendor_true on both tables,
    // incl. encode roundtrip).
    for tb in [t120(), IsaTable::load(std::path::Path::new("tables/sm103a.json")).unwrap()] {
        let idx = DecodeIndex::build(&tb);
        let sink_word: u128 = 0x000f_e200_0000_0000_0000_0000_0000_0980;
        let d = idx.decode(sink_word, 0, &tb)
            .expect("b4fill4: sink word decodes to its vendor-true LD.EF.U8 row");
        assert_eq!(cubit::printer::to_sass(&d), "@P0 LD.EF.U8 R0, [R0]");
    }
}

