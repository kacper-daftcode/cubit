#!/usr/bin/env python3
"""Generate docs/TESTS.md - the index of the test suite - from the `//!` doc comments of tests/*.rs.

Every test file starts with a `//!` paragraph that says what it guards; this script collects
the first paragraph of each file, the number of `#[test]` functions, and groups the files:

  bugNNN_*          the encoder/decoder guard specification: one file per numbered bug, in order
  sm120_*, dsv41_*  measured SM120 forms (nvdisasm fixtures under tests/fixtures/)
  mk*, mercury*     the Mercury companion-section emitter (nvcc 13.x `.nv.merc*` laws)
  ra_*, sched_*, render_*, stallfix*, reg_liveness, pred_liveness   the passes
  everything else   assembler / ELF / table / CLI behaviour

    python3 tools/gen_tests_index.py            # writes docs/TESTS.md
    python3 tools/gen_tests_index.py --check    # exit 1 if docs/TESTS.md is stale (CI)
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests"
OUT = ROOT / "docs" / "TESTS.md"


def first_paragraph(path: pathlib.Path) -> str:
    lines = []
    for line in path.read_text().splitlines():
        if line.startswith("//!"):
            text = line[3:].strip()
            if not text and lines:
                break
            if text:
                lines.append(text)
        elif lines:
            break
        elif line.strip() and not line.startswith("//"):
            break
    para = " ".join(lines)
    para = re.sub(r"\s+", " ", para).strip()
    return para


def group_of(name: str) -> str:
    if re.match(r"bug\d+", name):
        return "bug"
    if name.startswith(("sm120_", "dsv41_")):
        return "sm120"
    if name.startswith(("mk", "mercury")):
        return "mercury"
    if name.startswith(("ra_", "sched_", "render_", "stallfix", "reg_liveness", "pred_liveness")):
        return "passes"
    return "other"


def render() -> str:
    files = sorted(TESTS.glob("*.rs"))
    rows = []
    for f in files:
        n_tests = len(re.findall(r"^\s*#\[test\]", f.read_text(), re.M))
        rows.append((f.name, group_of(f.stem), first_paragraph(f), n_tests))
    total_tests = sum(r[3] for r in rows)
    out = ["# Test index", "",
           f"{len(rows)} test files, {total_tests} `#[test]` functions (generated by `tools/gen_tests_index.py` "
           "from the `//!` doc comment of each file; `cargo test` runs them all, `tools/sync_table.py` runs them "
           "as the table-sync gate).", "",
           "Conventions: a `bugNNN_*.rs` file is the executable specification of one numbered encoder/decoder "
           "finding (the number is the order the finding was made in, 2026-08..09 for most); the `//!` comment "
           "states the law it pins and the evidence. `sm120_*.rs` replay nvdisasm fixtures of measured forms "
           "(`tools/probes/`). `mk*`/`mercury*` pin the Mercury companion-section emitter. Fixtures live in "
           "`tests/fixtures/` (JSONL of words with NVIDIA's text; under 1 MB in total).", ""]
    sections = [("bug", "Encoder / decoder guards (`bugNNN_*`)"), ("sm120", "Measured SM120 forms"),
                ("mercury", "Mercury companion sections"), ("passes", "Passes: register allocation, scheduling, rendering, stall legalization, liveness"),
                ("other", "Assembler, ELF, tables, CLI")]
    for key, title in sections:
        sel = [r for r in rows if r[1] == key]
        if not sel:
            continue
        out += [f"## {title} ({len(sel)} files)", "", "| file | tests | what it guards |", "|---|---:|---|"]
        for name, _g, para, n in sel:
            para = para.replace("|", "\\|")
            if len(para) > 260:
                para = para[:257].rsplit(" ", 1)[0] + " …"
            out.append(f"| `{name}` | {n} | {para or '(no doc comment)'} |")
        out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_tests_index.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
